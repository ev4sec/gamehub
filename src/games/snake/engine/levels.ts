export interface Level {
  name: string;
  walls: Set<number>;
  portals: Portal[];
  start: Vec;
}

function parse(raw: RawLevel, index: number): Level {
  if (raw.rows.length !== GRID) {
    throw new Error(`Level ${index} "${raw.name}": ${raw.rows.length} rows, expected ${GRID}`);
  }

  const walls = new Set<number>();
  const marks: Record<string, Vec[]> = { P: [], Q: [] };
  let start: Vec | null = null;

  raw.rows.forEach((row, y) => {
    if (row.length !== GRID) {
      throw new Error(
        `Level ${index} "${raw.name}" row ${y}: ${row.length} chars, expected ${GRID}`,
      );
    }
    for (let x = 0; x < GRID; x++) {
      const ch = row[x];
      if (ch === '#') walls.add(cellKey(x, y));
      else if (ch === 'S') start = { x, y };
      else if (ch === 'P' || ch === 'Q') marks[ch].push({ x, y });
    }
  });

  if (!start) throw new Error(`Level ${index} "${raw.name}" has no S start marker`);

  const portals: Portal[] = [];
  for (const ch of ['P', 'Q'] as const) {
    const found = marks[ch];
    if (found.length === 0) continue;
    if (found.length !== 2) {
      throw new Error(
        `Level ${index} "${raw.name}": portal '${ch}' appears ${found.length} times, expected 2`,
      );
    }
    portals.push({ a: found[0], b: found[1] });
  }

  return { name: raw.name, walls, portals, start };
}

export const LEVELS: Level[] = RAW.map(parse);

/** Apples needed to clear a given maze level. */
export function levelQuota(level: number): number {
  return 6 + level * 2;
}

/** The plain bordered arena used by every mode except Maze. */
export function arenaWalls(): Set<number> {
  const walls = new Set<number>();
  for (let i = 0; i < GRID; i++) {
    walls.add(cellKey(i, 0));
    walls.add(cellKey(i, GRID - 1));
    walls.add(cellKey(0, i));
    walls.add(cellKey(GRID - 1, i));
  }
  return walls;
}
