/**
 * Writes src/games/codelab/engine/tsCompiled.ts: the JavaScript each
 * TypeScript predict snippet runs as in the browser.
 *
 * Run with `npm run gen:ts` after adding or editing a TypeScript predict
 * level. `npm run verify:levels` fails if the file on disk is stale, so a
 * forgotten run cannot ship.
 */
import { writeFileSync } from 'node:fs';
import { compileAll } from './ts-compile';

const OUT = 'src/games/codelab/engine/tsCompiled.ts';

const compiled = compileAll();
const body = Object.entries(compiled)
  .map(([source, js]) => `  [${JSON.stringify(source)}]:\n    ${JSON.stringify(js)},`)
  .join('\n');

writeFileSync(
  OUT,
  `/* Generated by \`npm run gen:ts\`. Do not edit by hand: change the level, then regenerate. */
export const COMPILED: Record<string, string> = {
${body}
};
`,
);
console.log(`wrote ${Object.keys(compiled).length} snippets to ${OUT}`);
